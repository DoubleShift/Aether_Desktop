// Generates src/i18n.zh.js from the human-maintained TSV dictionary.
//
// Why a generator instead of hand-writing the JS object: the upstream i18n keys
// are raw English sentences that contain \u2019, \u2011, escaped quotes and
// Windows paths (engine\\xray\\xray.exe). Writing 800+ of those by hand as JS
// string literals is a reliable way to produce mismatched keys. The TSV keeps
// the source text readable; this script normalises every key exactly the way
// the JavaScript engine would parse it and emits JSON.stringify'd literals.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC = path.join(root, 'scripts/zh-translations.tsv')
const OUT = path.join(root, 'src/i18n.zh.js')

/** Resolve JS string escapes (\u2019, \", \\, \') into the runtime key. */
function normalizeKey(raw) {
  // \' is valid in a single-quoted JS string but not in JSON.
  const cleaned = raw.replace(/\\'/g, "'")
  try {
    return JSON.parse(`"${cleaned}"`)
  } catch {
    // Keys with an escape JSON cannot read (e.g. a stray backslash) fall back
    // to a minimal unescape so the entry is still emitted.
    return cleaned.replace(/\\\\/g, '\\')
  }
}

// The AI assistant and Gemini chat were removed from this build. Their strings
// can never be rendered, so keep them out of the shipped dictionary entirely —
// otherwise dead "Gemini"/"Aether AI" text still ends up inside the JS bundle.
const AI_ONLY_KEY = [
  /Gemini/i, /Aether AI/i, /\bassistant\b/i, /\badvisor\b/i,
  /\bconversation\b/i, /^Chat\b/i, /Open the chat/i, /Chat with Gemini/i,
  /API key/i, /API connection/i, /AI Studio/i, /Checks the key/i,
  /Thinking…/i, /Proposed settings/i, /Discover models/i,
  /No models? discovered/i, /No model has been discovered/i,
  /Flash/i, /^Model: \{0\}/i, /model\(s\) available/i,
  /free quota/i, /Google\b/i, /Ask anything/i, /Ask about a setting/i,
  /Explain this more simply/i, /Copy answer/i, /Edit message/i,
  /Delete \{0\} message/i, /Deleted messages/i, /Everything after this message/i,
  /Tune for my network/i, /Analyse and tune/i, /Did not understand/i,
  /Clear the (whole )?conversation/i, /^Hi, I am/i, /^I can explain any setting/i,
  /Which protocol should I use on mobile data/i, /Why is my connection slow/i,
  /Explain MTU and pick/i, /Add a key first/i, /Add your Gemini/i,
  /A key ending in/i, /No key stored/i, /The key is stored sealed/i,
  /the selected model/i, /The answer was cut off/i, /The model returned no answer/i,
  /The request never reached Google/i, /Get a free key/i, /Test the API connection/i,
  /The assistant /i, /This key cannot use/i, /Saved for the next connection/i,
  /Refused by the app/i, /Nothing needed changing/i, /Working — \{0\}/i,
  /^Ask Aether AI/i, /^Clear conversation$/i, /^Clear the conversation$/i,
]

const entries = new Map()
let skipped = 0
let lineNo = 0
for (const line of fs.readFileSync(SRC, 'utf8').split(/\r?\n/)) {
  lineNo++
  const text = line.trim()
  if (!text || text.startsWith('#')) continue
  const sep = text.indexOf('|||')
  if (sep < 0) {
    throw new Error(`zh-translations.tsv:${lineNo}: missing ||| separator`)
  }
  const key = normalizeKey(text.slice(0, sep).trim())
  const value = text.slice(sep + 3).trim()
  if (!key || !value) {
    throw new Error(`zh-translations.tsv:${lineNo}: empty key or translation`)
  }
  if (AI_ONLY_KEY.some((re) => re.test(key))) { skipped++; continue }
  entries.set(key, value)
}

const body = [...entries.entries()]
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n')

fs.writeFileSync(OUT, [
  '// Generated by scripts/gen-zh-module.mjs — do not edit by hand.',
  '// Source of truth: scripts/zh-translations.tsv',
  '// Simplified Chinese dictionary for Aether Desktop. Keys are the English',
  '// source strings used by t() in the upstream code.',
  `// ${entries.size} entries.`,
  'export const ZH = {',
  body,
  '}',
  '',
].join('\n'), 'utf8')

console.log(`Generated src/i18n.zh.js with ${entries.size} entries (${skipped} AI-only strings excluded)`)
